# ------------------------------------------------------------------ alert management
with tab_alerts:
    st.subheader("Verify alerts")
    al = alerts_df(500)
    pend = al[al["Status"] == "Pending"]
    if user["role"] != "Security Personnel":
        st.info("Only security personnel can confirm or reject alerts. You can view them below.")
    elif len(pend):
        options = {f"#{r.Alert} · {r.Time} · {r.Node} · {r.Event} ({r.Confidence:.0%})": int(r.Alert)
                   for r in pend.itertuples()}
        choice = st.selectbox("Pending alert", list(options))
        aid = options[choice]
        row = al[al["Alert"] == aid].iloc[0]
        st.write(f"**Location:** {row.latitude:.5f}, {row.longitude:.5f} · **Site:** {row.Site} · "
                 f"**Priority:** {row.Priority} · **Delivered by:** {row.Channel}")
        action = st.text_input("Action taken", "Response team dispatched to GPS position")
        b1, b2 = st.columns(2)
        for label, status, col in [("✅ Confirm threat", "Confirmed", b1), ("❌ Mark as false alert", "False alert", b2)]:
            if col.button(label):
                sim.con.execute("UPDATE alert SET verification_status=? WHERE alert_id=?", (status, aid))
                sim.con.execute("INSERT INTO response (alert_id, user_id, action_taken, response_time) VALUES (?,?,?,?)",
                                (aid, user["user_id"], action if status == "Confirmed" else "Marked as false alert",
                                 datetime.now().isoformat(sep=" ", timespec="seconds")))
                sim.con.commit()
                st.rerun()
    else:
        st.success("No pending alerts.")
    st.subheader("Alert history")
    st.dataframe(al.drop(columns=["latitude", "longitude"]), hide_index=True)
    st.download_button("Download alert log (CSV)", al.to_csv(index=False), "alerts.csv", "text/csv")

