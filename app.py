# ------------------------------------------------------------------ signal viewer
with tab_signal:
    ev = sim.last_event
    if ev is None:
        st.info("No event processed yet. Start the simulation or trigger a test event.")
    else:
        e = ev["event"]
        st.markdown(f"**{ev['time']} · {ev['device']}** · predicted **{class_name(ev['pred'])}** "
                    f"with {ev['conf']:.1%} confidence · {'alert sent' if ev['alerted'] else 'no alert'}")
        t_ms = np.arange(len(e["vibration"])) / FS * 1000
        step = 8
        c1, c2 = st.columns(2)
        c1.markdown("**Vibration (pipe)**")
        c1.line_chart(pd.DataFrame({"time (ms)": t_ms[::step], "vibration": e["vibration"][::step]}),
                      x="time (ms)", y="vibration")
        c2.markdown("**Acoustic**")
        c2.line_chart(pd.DataFrame({"time (ms)": t_ms[::step], "acoustic": e["acoustic"][::step]}),
                      x="time (ms)", y="acoustic")
        c3, c4 = st.columns(2)
        spec = np.abs(np.fft.rfft(e["vibration"] * np.hanning(len(e["vibration"]))))
        f = np.fft.rfftfreq(len(e["vibration"]), 1 / FS)
        keep = f <= 2500
        c3.markdown("**Vibration spectrum (0–2.5 kHz)**")
        c3.area_chart(pd.DataFrame({"frequency (Hz)": f[keep][::2], "magnitude": spec[keep][::2]}),
                      x="frequency (Hz)", y="magnitude")
        c4.markdown("**Light sensors (4 photodiodes)**")
        c4.line_chart(pd.DataFrame(e["light"].T, columns=[f"PD{i + 1}" for i in range(4)]))
        st.markdown("**Classifier output (softmax probabilities)**")
        st.bar_chart(pd.Series(ev["probs"], index=[SHORT[i] for i in range(5)]))

# ------------------------------------------------------------------ model performance
with tab_model:
    path = "results/metrics.json"
    if not os.path.exists(path):
        st.warning("results/metrics.json not found. Run `python train.py`.")
    else:
        res = json.load(open(path))
        d = res["dataset"]
        st.subheader("Offline evaluation on the simulated test set")
        st.caption(f"{d['events']:,} simulated events ({d['per_class']} per class) · "
                   f"{d['features']} features · split {d['train']}/{d['validation']}/{d['test']}")
        rows = [{"Model": k, "Accuracy": v["accuracy"], "Macro F1": v["macro_f1"],
                 "Inference time on PC (ms)": v["inference_ms"], "Model size (kB)": v["size_kb"]}
                for k, v in res["models"].items()]
        st.dataframe(pd.DataFrame(rows), hide_index=True)
        if "tcn_parameters" in res:
            st.caption(f"TCN parameters: {res['tcn_parameters']:,}. Inference time on the ESP32 must be measured on the board.")
        a, b = st.columns(2)
        with a:
            st.markdown("**Ablation study (Random Forest)**")
            st.bar_chart(pd.Series(res["ablation"]))
        with b:
            model_names = list(res["models"])
            pick = st.selectbox("Confusion matrix for", model_names, index=len(model_names) - 1)
            img = f"results/confusion_{pick.lower().replace(' ', '_')}.png"
            if os.path.exists(img):
                st.image(img)
        if res.get("history"):
            st.markdown("**Training curves (validation accuracy)**")
            st.line_chart(pd.DataFrame({k: pd.Series(v.get("val_accuracy", [])) for k, v in res["history"].items()}))

    st.subheader("Live performance in this simulation session")
    lg = query(sim.con, "SELECT true_class, predicted_class, alerted FROM event_log")
    if len(lg):
        threat = lg["true_class"].isin(THREAT_CLASSES)
        tp = int((lg["alerted"].astype(bool) & threat).sum())
        fp = int((lg["alerted"].astype(bool) & ~threat).sum())
        fn = int((~lg["alerted"].astype(bool) & threat).sum())
        acc = float((lg["true_class"] == lg["predicted_class"]).mean())
        m = st.columns(5)
        m[0].metric("Events processed", len(lg))
        m[1].metric("Classification accuracy", f"{acc:.1%}")
        m[2].metric("Threats detected", tp)
        m[3].metric("False alerts", fp)
        m[4].metric("Missed threats", fn)
        st.caption("Ground truth is known only because the events are simulated.")
    else:
        st.info("No events yet.")
